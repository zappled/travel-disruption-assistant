/**
 * Rules-only assessment, used when the AI is unavailable (no key, outage,
 * refusal). Deliberately conservative and simple — the point is that the
 * user still gets an evidence-backed answer.
 */
import type { Assessment, Recommendation, Risk, RiskLevel, Signal, SignalKind } from "./types.js";

const KIND_LABEL: Record<SignalKind, string> = {
  ground_stop: "FAA ground stop",
  ground_delay: "FAA ground delay program",
  airport_delay: "Airport delays",
  closure: "Airport closure",
  nws_alert: "Weather alert",
  thunderstorm: "Thunderstorms",
  snow_ice: "Snow or ice",
  high_wind: "Strong winds",
  low_visibility: "Low cloud / fog",
  heavy_rain: "Heavy rain",
  fair_weather: "Fair weather",
};

const KIND_ADVICE: Partial<Record<SignalKind, Recommendation>> = {
  ground_stop: { action: "Check your flight status now and ask your airline about rebooking.", reason: "Flights to the affected airport are being held on the ground.", priority: "now" },
  ground_delay: { action: "Expect delays; check your flight status before leaving for the airport.", reason: "The FAA is metering traffic into this airport.", priority: "day_of_travel" },
  thunderstorm: { action: "Prefer an earlier flight if you can — storms typically build in the afternoon.", reason: "Thunderstorms cause ground stops and diversions.", priority: "before_travel" },
  snow_ice: { action: "Check whether your airline has issued a travel waiver, and allow extra time for de-icing.", reason: "Snow and ice slow airport operations and can cause cancellations.", priority: "before_travel" },
  low_visibility: { action: "Allow for arrival delays; low cloud reduces how many flights can land per hour.", reason: "Low ceilings often trigger ground delay programs.", priority: "day_of_travel" },
  high_wind: { action: "Monitor your flight status; strong crosswinds can reduce runway capacity.", reason: "High winds can cause delays and bumpy approaches.", priority: "day_of_travel" },
  closure: { action: "Confirm your flight is still operating with the airline.", reason: "A published closure overlaps your travel date.", priority: "now" },
};

export function rulesAssessment(signals: Signal[], daysAhead: number): Omit<Assessment, "confidence" | "confidenceReason"> {
  const adverse = signals.filter((s) => s.severity > 0);
  const max = Math.max(0, ...adverse.map((s) => s.severity));
  const count = (sev: number) => adverse.filter((s) => s.severity === sev).length;

  let overallRisk: RiskLevel = "low";
  if (max === 3) overallRisk = "severe";
  else if (max === 2) overallRisk = count(2) >= 2 ? "high" : "moderate";
  else if (max === 1 && count(1) >= 3) overallRisk = "moderate";

  // One risk per signal kind, citing every signal of that kind.
  const byKind = new Map<SignalKind, Signal[]>();
  for (const s of adverse) byKind.set(s.kind, [...(byKind.get(s.kind) ?? []), s]);
  const risks: Risk[] = [...byKind.entries()].map(([kind, list]) => {
    const top = Math.max(...list.map((s) => s.severity));
    return {
      title: KIND_LABEL[kind],
      airports: [...new Set(list.map((s) => s.airport))],
      likelihood: top >= 2 ? "likely" : "possible",
      impact: top === 3 ? "major" : top === 2 ? "moderate" : "minor",
      explanation: list.map((s) => s.summary).join("; "),
      evidenceIds: list.map((s) => s.id),
    };
  });

  const recommendations: Recommendation[] = [...byKind.keys()]
    .map((k) => KIND_ADVICE[k])
    .filter((r): r is Recommendation => Boolean(r));
  if (daysAhead >= 3) {
    recommendations.push({ action: "Check again 1–2 days before you fly.", reason: "Forecasts this far out change.", priority: "before_travel" });
  }
  if (recommendations.length === 0) {
    recommendations.push({ action: "No action needed — check your flight status on the day as usual.", reason: "No significant disruption signals found.", priority: "day_of_travel" });
  }

  // The UI shows the level as a badge, so the headline says what, not how bad.
  const kinds = risks.slice(0, 2).map((r) => r.title.toLowerCase()).join(" and ");
  const headline = overallRisk === "low" ? "No significant disruption signals" : `${kinds[0].toUpperCase()}${kinds.slice(1)}`;

  return {
    overallRisk,
    headline,
    summary:
      adverse.length === 0
        ? "None of the sources show weather or air-traffic problems at your airports for this date."
        : `Found ${adverse.length} signal(s) worth knowing about. This summary was generated by rules because the AI assessment was unavailable.`,
    risks,
    recommendations,
    generatedBy: "rules",
  };
}
